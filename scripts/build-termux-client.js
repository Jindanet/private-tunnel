'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { builtinModules } = require('node:module');
const esbuild = require('esbuild');

async function build() {
  const root = path.resolve(__dirname, '..');
  const projectLicense = fs.readFileSync(path.join(root, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n').trim();
  const wsRoot = path.dirname(require.resolve('ws'));
  const ws = JSON.parse(fs.readFileSync(path.join(wsRoot, 'package.json'), 'utf8'));
  const license = fs.readFileSync(path.join(wsRoot, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n').trim();
  const result = await esbuild.build({
    absWorkingDir: root,
    entryPoints: ['client/bin/ptunnel.js'],
    outfile: 'ptunnel.js',
    bundle: true,
    write: false,
    platform: 'node',
    target: 'node22.12',
    format: 'cjs',
    charset: 'utf8',
    minifySyntax: true,
    legalComments: 'inline',
    metafile: true,
    // Avoid bundling the unused WebSocket server and optional native addons.
    alias: { ws: path.join(wsRoot, 'lib', 'websocket.js') },
    define: { '__PTUNNEL_STANDALONE__': 'true', 'process.env.WS_NO_BUFFER_UTIL': '"1"', 'process.env.WS_NO_UTF_8_VALIDATE': '"1"' },
    external: ['bufferutil', 'utf-8-validate'],
    banner: { js: `// Generated by npm run build:termux. Edit client/ sources, then rebuild.\n// Standalone client: Node.js only; no npm or native modules required.\n/* PrivateTunnel:\n${projectLicense}\n\nBundled ws ${ws.version} (MIT):\n${license}\n*/` },
  });
  for (const output of Object.values(result.metafile.outputs)) {
    for (const item of output.imports) {
      if (item.external && !builtinModules.includes(item.path.replace(/^node:/, ''))) {
        throw new Error(`Standalone client still depends on ${item.path}`);
      }
    }
  }
  const filename = path.join(root, 'ptunnel.js');
  const content = result.outputFiles[0].text;
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(filename) || fs.readFileSync(filename, 'utf8').replace(/\r\n/g, '\n') !== content) {
      throw new Error('ptunnel.js is stale. Run npm run build:termux and commit the generated file.');
    }
    console.log('Standalone Termux client is up to date.');
  } else {
    fs.writeFileSync(filename, content, { mode: 0o755 });
    console.log(`Built ptunnel.js (${Math.ceil(Buffer.byteLength(content) / 1024)} KiB).`);
  }
}

build().catch((error) => { console.error(error.message); process.exitCode = 1; });
